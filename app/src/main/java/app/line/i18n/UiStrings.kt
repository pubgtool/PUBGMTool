    fun translate(context: Context, text: String): String {
        val id = ids[text] ?: when {
            text.startsWith("Диалог ") -> return context.getString(R.string.accessibility_conversation_prefix) + text.removePrefix("Диалог ")
            text.contains("\n\n") && text.endsWith("Используйте код только из доверенного источника.") ->
                return context.getString(R.string.connect_server_confirmation, text.substringBefore("\n\n"))
            else -> return text
        }
        return context.getString(id)
    }
